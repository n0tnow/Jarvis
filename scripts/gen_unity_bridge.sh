#!/bin/zsh
# Regenerates Sources/Jarvis/Unity/UnityBridgePackage.generated.swift from UnityBridge/com.jarvis.bridge (the single source of the Editor bridge).
# The package is embedded so the app needs no resource lookup; a unit test fails if this file is stale.
set -euo pipefail
cd "$(dirname "$0")/.."
python3 - <<'PY'
import os
root = "UnityBridge/com.jarvis.bridge"
files = []
for d, _, names in os.walk(root):
    for n in sorted(names):
        p = os.path.join(d, n)
        if n.endswith(".meta") or n == ".DS_Store": continue
        files.append((os.path.relpath(p, root), open(p, encoding="utf-8").read()))
files.sort()
out = ["// GENERATED by scripts/gen_unity_bridge.sh from UnityBridge/com.jarvis.bridge — do not edit by hand.", "import Foundation", "",
       "enum UnityBridgePackage {", "    static let folderName = \"com.jarvis.bridge\"", "    static let files: [(path: String, content: String)] = ["]
for rel, text in files:
    out.append('        ("%s", ###"""' % rel)
    out.append(text.rstrip("\n"))
    out.append('"""###),')
out.append("    ]")
out.append("}")
open("Sources/Jarvis/Unity/UnityBridgePackage.generated.swift", "w", encoding="utf-8").write("\n".join(out) + "\n")
PY
echo "generated"
